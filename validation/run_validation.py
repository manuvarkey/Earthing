#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Run the standards validation and print a report.

Usage (from the repository root):

    python3 validation/run_validation.py                 # all cases
    python3 validation/run_validation.py --skip-numerical
    python3 validation/run_validation.py --report validation/report.md

Exit status is 1 if any case fails or raises an error, otherwise 0.
"""

from __future__ import annotations

import argparse
import os
import sys
import time
from collections import Counter, OrderedDict

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from cases import NUMERICAL, all_cases, evaluate  # noqa: E402


def _fmt(value):
    if value is None:
        return "-"
    magnitude = abs(value)
    if magnitude == 0:
        return "0"
    if magnitude >= 1000:
        return "{:.1f}".format(value)
    if magnitude >= 1:
        return "{:.4g}".format(value)
    return "{:.4g}".format(value)


def _dev(result):
    d = result.deviation
    return "-" if d is None else "{:+.2f} %".format(d * 100)


def run(skip_numerical=False, only=None):
    cases = all_cases()
    if skip_numerical:
        cases = [c for c in cases if c.kind != NUMERICAL]
    if only:
        cases = [c for c in cases if only.lower() in c.id.lower()]
    results = []
    for case in cases:
        t0 = time.time()
        result = evaluate(case)
        result.elapsed = time.time() - t0
        results.append(result)
        flag = {"PASS": ".", "FAIL": "F", "INFO": "i", "ERROR": "E"}[result.status]
        print(flag, end="", flush=True)
    print()
    return results


def print_console(results):
    groups = OrderedDict()
    for r in results:
        groups.setdefault(r.case.standard, []).append(r)
    for standard, rs in groups.items():
        print("\n== {} ==".format(standard))
        header = "{:<34} {:>6} {:>12} {:>12} {:>9} {:>10}".format(
            "case", "status", "computed", "reference", "dev", "tol")
        print(header)
        print("-" * len(header))
        for r in rs:
            print("{:<34} {:>6} {:>12} {:>12} {:>9} {:>10}".format(
                r.case.id[:34], r.status, _fmt(r.computed), _fmt(r.case.reference),
                _dev(r), r.case.tolerance_text()))
            if r.status == "ERROR":
                print("    " + r.error)

    attention = [r for r in results if r.status in ("FAIL", "ERROR")]
    if attention:
        print("\nCases needing attention:")
        for r in attention:
            print("  {} [{}] {}: {}".format(r.status, r.case.function, r.case.id,
                                             r.case.description))
            print("     source: {} {}".format(r.case.standard, r.case.clause))
            if r.case.note:
                print("     note: " + r.case.note)
            if r.error:
                print("     error: " + r.error)

    counts = Counter(r.status for r in results)
    print("\nSummary: {} cases - {} passed, {} failed, {} errors, {} informational".format(
        len(results), counts["PASS"], counts["FAIL"], counts["ERROR"], counts["INFO"]))


def write_markdown(results, path):
    counts = Counter(r.status for r in results)
    lines = [
        "# Validation report",
        "",
        "Generated by `validation/run_validation.py`.",
        "",
        "**{} cases:** {} passed, {} failed, {} errors, {} informational.".format(
            len(results), counts["PASS"], counts["FAIL"], counts["ERROR"], counts["INFO"]),
        "",
    ]
    groups = OrderedDict()
    for r in results:
        groups.setdefault(r.case.standard, []).append(r)
    for standard, rs in groups.items():
        lines += ["## " + standard, "",
                  "| Case | Function | Source | Computed | Reference | Deviation | Tolerance | Status |",
                  "| --- | --- | --- | ---: | ---: | ---: | --- | --- |"]
        for r in rs:
            lines.append("| {} | `{}` | {} | {} | {} {} | {} | {} | {} |".format(
                r.case.id, r.case.function, r.case.clause, _fmt(r.computed),
                _fmt(r.case.reference), r.case.unit, _dev(r),
                r.case.tolerance_text(), r.status))
        lines.append("")
    notes = [r for r in results if r.case.note or r.error]
    if notes:
        lines += ["## Notes", ""]
        seen = set()
        for r in notes:
            text = r.case.note + ((" Error: " + r.error) if r.error else "")
            key = (r.case.function, text)
            if key in seen and not r.error:
                continue
            seen.add(key)
            lines.append("- **{}** ({}): {}".format(r.case.id, r.status, text.strip()))
        lines.append("")
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    print("Report written to " + path)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--skip-numerical", action="store_true",
                        help="skip the Network solver cases (about 30 s and 1 GB RAM)")
    parser.add_argument("--only", metavar="TEXT",
                        help="run only cases whose id contains TEXT")
    parser.add_argument("--report", metavar="PATH",
                        help="also write a Markdown report to PATH")
    args = parser.parse_args(argv)

    results = run(args.skip_numerical, args.only)
    print_console(results)
    if args.report:
        write_markdown(results, args.report)
    return 1 if any(r.status in ("FAIL", "ERROR") for r in results) else 0


if __name__ == "__main__":
    sys.exit(main())
